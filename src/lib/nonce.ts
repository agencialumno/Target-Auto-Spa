// Nonce para o "Sign in with Apple": o app envia o SHA-256 (hex) à Apple e entrega o nonce
// original ao Firebase, que confere se o idToken foi emitido para esta tentativa de login.

export function gerarNonce(tamanho = 32): string {
  const alfabeto = '0123456789ABCDEFGHIJKLMNOPQRSTUVXYZabcdefghijklmnopqrstuvwxyz-._';
  const bytes = new Uint8Array(tamanho);
  crypto.getRandomValues(bytes);
  return Array.from(bytes, (b) => alfabeto[b % alfabeto.length]).join('');
}

